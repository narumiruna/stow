#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mapping_is_sorted_unique_and_idempotent() {
        assert!(WIDTH_MAP.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for &(from, to) in WIDTH_MAP {
            let source = char::from_u32(from).unwrap().to_string();
            let target = char::from_u32(to).unwrap().to_string();
            assert_eq!(fold(&source), target);
            assert_eq!(fold(&target), target);
        }
        assert_eq!(fold("ㄱㄴㄷ"), "\u{ffa1}\u{ffa4}\u{ffa7}");
        assert_eq!(fold("가"), "가");
        assert_eq!(fold("ガイド"), "ｶﾞｲﾄﾞ");
        assert_eq!(fold("① ﬃ Café"), "① ﬃ Café");
    }
}
