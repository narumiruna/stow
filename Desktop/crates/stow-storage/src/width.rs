use unicode_normalization::UnicodeNormalization;

pub(crate) fn fold(text: &str) -> String {
    let mut result = String::with_capacity(text.len());
    for character in text.chars() {
        if let Some(mapped) = mapped(character) {
            result.push(mapped);
            continue;
        }
        // Convert composed voiced kana only when each canonical component has
        // a width mapping. Do not decompose unrelated letters or Hangul syllables.
        if !('\u{30a0}'..='\u{30ff}').contains(&character) {
            result.push(character);
            continue;
        }
        let decomposed = character.to_string().nfd().collect::<Vec<_>>();
        if decomposed.len() > 1 && decomposed.iter().all(|part| mapped(*part).is_some()) {
            result.extend(decomposed.into_iter().map(|part| mapped(part).unwrap()));
        } else {
            result.push(character);
        }
    }
    result
}

fn mapped(character: char) -> Option<char> {
    let index = WIDTH_MAP
        .binary_search_by_key(&(character as u32), |pair| pair.0)
        .ok()?;
    char::from_u32(WIDTH_MAP[index].1)
}

